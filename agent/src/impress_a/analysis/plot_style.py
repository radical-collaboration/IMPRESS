"""Shared figure style for this project's campaign figures.

Generated by the `campaign-plot-style` skill, then given this project's four
arms. Leave the conventions alone so figures from different studies stay
readable side by side; `RUN_STYLES` and `WINDOW_S` are the parts that are ours.

**The entity a hue names here is a KNOB SETTING, not an allocation.** The arms
of `analysis/mock_lab.py` are four settings of one laptop surrogate, tiered by
what the campaign does under each, and a figure drawn from a sweep rather than
from the arms uses `NEUTRAL_SERIES` - the swept line is a measure, not one of
the four compared entities, and drawing it in an arm's hue would claim it was.

The visual conventions are the group's campaign plot scripts': the type scale,
a `#DCD7CC` recessive grid drawn under the data, top and right spines dropped,
white-faced round markers, 150 dpi, a framed legend.

The palette is a **performance tier** palette. The blue slot means "the
best-performing configuration" — the one the report is arguing for — and the
lower-performing configurations get their own hues:

    #2176c7  blue      best performance
    #ae8a16  ochre     lower performance
    #9e3f1c  brick     lowest performance
    #993284  magenta   did not complete (evidence, never a rate)

Colour follows the *run*, not its rank on whatever axis a given figure shows,
so a run keeps its hue across every figure even where the ranking inverts
between per-pipeline and per-GPU normalisations.

All four pass every check in the `dataviz` validator against a white surface,
on adjacent pairs and on all pairs:

    node validate_palette.js "#2176c7,#ae8a16,#9e3f1c,#993284" \
        --mode light --surface "#ffffff" --pairs all

Worst all-pairs separation is magenta-blue at deutan dE 10.9, above the 8.0
target; every slot clears 3:1 contrast. Tritan separation on that pair is 4.7,
which is why every series also carries a direct label or a distinct line style.
Adding a fifth hue means re-running that command and fixing every FAIL.
"""

from dataclasses import dataclass

import matplotlib.pyplot as plt

# -- Ink, surface, grid ------------------------------------------------------
SURFACE = "#ffffff"
INK = "#1a1a1a"            # titles, numerals on the surface
INK_SECONDARY = "#444444"  # captions and provenance notes
GRID = "#DCD7CC"
# A measure that is not one of the compared entities — a manager-occupancy
# trace in a panel whose colour is already spent on the run. Neutral by
# intent: it must not read as one more run.
NEUTRAL_SERIES = "#5b5b55"

# A two-state contrast inside one figure — before/after, full-run vs
# equal-window. Deliberately not taken from RUN_STYLES: on a figure already
# comparing two runs, a run hue used for a *state* reads as one of those runs.
# The pair separates on chroma as well as hue, so it survives every CVD
# simulation; it is exempt from the categorical chroma floor for that reason,
# and always ships with a legend.
CONTRAST = {"before": "#5b5b55", "after": "#117a79"}


@dataclass(frozen=True)
class RunStyle:
    """Everything a figure needs to draw one run consistently."""
    label: str      # full legend label
    short: str      # axis-tick / annotation label
    color: str      # validated categorical hex — lines, markers, bar fills
    cmap: str       # for density and sequential uses
    marker: str
    tier: str       # "best" | "lower" | "lowest" | "failed"


# The four arms of the mock small-molecule campaign, tiered by what the campaign
# DOES under each - not by any number the surrogate reports, which is a seeded
# draw. The tiers are assigned once, here, and never move between figures.
#
#   baseline   shipped defaults; every bar cleared, the Spec satisfied
#   rescued    the same difficulty as `hard`, bought back with three knobs
#   hard       difficulty 0.55: acceptance shortfall, empty front, trust intact
#   hopeless   difficulty 0.85: integrity failure, campaign aborted
#
# `hopeless` takes the magenta slot because it is the run that DID NOT COMPLETE:
# `CampaignAborted` after three consecutive all-failed runs. The slot's rule
# applies unchanged - it is evidence, and it is never drawn as a rate.
RUN_STYLES: dict[str, RunStyle] = {
    "baseline": RunStyle(
        label="baseline - shipped defaults", short="baseline",
        color="#2176c7", cmap="Blues", marker="o", tier="best"),
    "rescued": RunStyle(
        label="rescued - difficulty 0.55, three knobs raised", short="rescued",
        color="#ae8a16", cmap="YlOrBr", marker="s", tier="lower"),
    "hard": RunStyle(
        label="hard - difficulty 0.55 at defaults", short="hard",
        color="#9e3f1c", cmap="OrRd", marker="^", tier="lowest"),
    "hopeless": RunStyle(
        label="hopeless - difficulty 0.85, aborted", short="hopeless",
        color="#993284", cmap="RdPu", marker="X", tier="failed"),
}

# -- the second categorical: which control model drove the cell -------------
# The four validated hues are spent on the four knob arms, and colour follows
# the entity. A reasoner axis is a SECOND four-member categorical over the same
# figures, and giving it hues would either need four more validated colours or
# make one hue mean two things in one report - both of which the palette rules
# forbid for the same reason.
#
# So the model takes the FILL channel instead: hatch and face alpha, inside the
# arm's own hue. It survives every CVD simulation by construction (it is not a
# colour difference), it reads in greyscale, and the arm identity a reader
# already learned from f1-f6 carries straight into f7-f9. Every series also
# carries a direct label, as everything here does.
MODEL_FILLS: dict[str, dict] = {
    "D": {"hatch": "", "alpha": 1.0},
    "null": {"hatch": "..", "alpha": 0.30},
    "A": {"hatch": "//", "alpha": 0.65},
    "B": {"hatch": "xx", "alpha": 0.65},
}
#: Marker per model, for the panels where a model is a point rather than a bar.
MODEL_MARKERS = {"D": "o", "null": ".", "A": "^", "B": "s"}


def model_fill(model: str) -> dict:
    """Fill keywords for one control model. Unknown is a bug, as with `style_for`."""
    try:
        return dict(MODEL_FILLS[model])
    except KeyError:
        raise KeyError(f"no fill for model {model!r}; known: {sorted(MODEL_FILLS)}") from None


# The equal window, IN SECONDS rather than the skill's minutes, because these
# campaigns finish in about one: a 60-minute window would be every run in full
# and the constant would mean nothing. Same rule, same reason - a cross-arm time
# series drawn to each arm's own end compares a deeper search against a shallower
# one. Set from the shortest arm that completes; `mock_figures` recomputes it from
# the collected table and falls back to this.
#
# No figure in `mock_figures` currently needs it: the decision-rate panel puts the
# DECISION INDEX on x and elapsed seconds on y, so depth is a visible axis rather
# than a hidden one, and the only wall-clock series is a single-run anatomy, which
# the skill exempts because the window would delete the thing it shows. The
# constant stays because the next cross-arm series will need it.
WINDOW_S = 1.0

# Best to worst, which is also the order the activity walks them in. CLEAN_ORDER
# is the arms whose campaign ran to a stop condition of its own and are therefore
# comparable on rate; an aborted arm is evidence, not a rate.
ORDER = list(RUN_STYLES)
CLEAN_ORDER = [j for j, s in RUN_STYLES.items() if s.tier != "failed"]
BEST = next((j for j, s in RUN_STYLES.items() if s.tier == "best"), None)


def style_for(job: str) -> RunStyle:
    """Style for a run key. An unknown key is a bug, not a fallback case:
    silently inventing a hue would break the across-figure colour identity the
    report relies on."""
    try:
        return RUN_STYLES[job]
    except KeyError:
        raise KeyError(f"no style for run {job!r}; known: {sorted(RUN_STYLES)}") from None


def solid_color(cmap_name: str, alpha: float = 0.65):
    """A single solid RGBA sampled from a named colormap — the campaign
    scripts' `style.solid_color`, kept so a figure ported from there behaves
    identically."""
    return plt.get_cmap(cmap_name)(alpha)


