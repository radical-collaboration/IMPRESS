"""Shared figure style for this project's campaign figures.

Generated by the `campaign-plot-style` skill. Edit `RUN_STYLES` to name this
project's runs; leave the conventions alone so figures from different studies
stay readable side by side.

The visual conventions are the group's campaign plot scripts': the type scale,
a `#DCD7CC` recessive grid drawn under the data, top and right spines dropped,
white-faced round markers, 150 dpi, a framed legend.

The palette is a **performance tier** palette. The blue slot means "the
best-performing configuration" — the one the report is arguing for — and the
lower-performing configurations get their own hues:

    #2176c7  blue      best performance
    #ae8a16  ochre     lower performance
    #9e3f1c  brick     lowest performance
    #993284  magenta   did not complete (evidence, never a rate)

Colour follows the *run*, not its rank on whatever axis a given figure shows,
so a run keeps its hue across every figure even where the ranking inverts
between per-pipeline and per-GPU normalisations.

All four pass every check in the `dataviz` validator against a white surface,
on adjacent pairs and on all pairs:

    node validate_palette.js "#2176c7,#ae8a16,#9e3f1c,#993284" \
        --mode light --surface "#ffffff" --pairs all

Worst all-pairs separation is magenta-blue at deutan dE 10.9, above the 8.0
target; every slot clears 3:1 contrast. Tritan separation on that pair is 4.7,
which is why every series also carries a direct label or a distinct line style.
Adding a fifth hue means re-running that command and fixing every FAIL.
"""

from dataclasses import dataclass

import matplotlib.pyplot as plt

# -- Ink, surface, grid ------------------------------------------------------
SURFACE = "#ffffff"
INK = "#1a1a1a"            # titles, numerals on the surface
INK_SECONDARY = "#444444"  # captions and provenance notes
GRID = "#DCD7CC"
# A measure that is not one of the compared entities — a manager-occupancy
# trace in a panel whose colour is already spent on the run. Neutral by
# intent: it must not read as one more run.
NEUTRAL_SERIES = "#5b5b55"

# A two-state contrast inside one figure — before/after, full-run vs
# equal-window. Deliberately not taken from RUN_STYLES: on a figure already
# comparing two runs, a run hue used for a *state* reads as one of those runs.
# The pair separates on chroma as well as hue, so it survives every CVD
# simulation; it is exempt from the categorical chroma floor for that reason,
# and always ships with a legend.
CONTRAST = {"before": "#5b5b55", "after": "#117a79"}


@dataclass(frozen=True)
class RunStyle:
    """Everything a figure needs to draw one run consistently."""
    label: str      # full legend label
    short: str      # axis-tick / annotation label
    color: str      # validated categorical hex — lines, markers, bar fills
    cmap: str       # for density and sequential uses
    marker: str
    tier: str       # "best" | "lower" | "lowest" | "failed"


# EDIT ME: one entry per run, keyed however the project keys its runs (a job
# id, a campaign slug). Tiers are assigned once, by the result the report
# argues, and then never move.
RUN_STYLES: dict[str, RunStyle] = {
    # Tiers by passing folds per GPU-hour, the headline of the 2026-10-17
    # non-adaptive benchmark (smb 23).
    "22927576": RunStyle(
        label="adaptive (22927576)", short="adaptive",
        color="#ae8a16", cmap="YlOrBr", marker="s", tier="lower"),
    "22967619": RunStyle(
        label="pass-through (22967619)", short="pass-through",
        color="#2176c7", cmap="Blues", marker="o", tier="best"),
    # Tied with pass-through on yield (51.4 vs 51.0 passing folds/GPU-h), so
    # the tier here is not a ranking against it -- blue was assigned to
    # pass-through first and colour follows the entity, never its rank.
    "22999614": RunStyle(
        label="naive / open-loop (22999614)", short="naive",
        color="#9e3f1c", cmap="OrRd", marker="^", tier="lowest"),
}

# The equal window, in minutes. Wall clocks differ between runs, and a time
# series drawn to each run's own end compares a deep search against a shallow
# one rather than comparing the configurations. Every time series that puts more
# than one run on the same axis is cut here; a single-run anatomy is not a
# comparison and keeps its full span. Set it from the shortest run.
WINDOW_MIN = 60

# Slowest to fastest. CLEAN_ORDER is the runs that reached their wall clock and
# are therefore comparable on rate; a failed run is evidence, not a rate.
ORDER = list(RUN_STYLES)
CLEAN_ORDER = [j for j, s in RUN_STYLES.items() if s.tier != "failed"]
BEST = next((j for j, s in RUN_STYLES.items() if s.tier == "best"), None)


def style_for(job: str) -> RunStyle:
    """Style for a run key. An unknown key is a bug, not a fallback case:
    silently inventing a hue would break the across-figure colour identity the
    report relies on."""
    try:
        return RUN_STYLES[job]
    except KeyError:
        raise KeyError(f"no style for run {job!r}; known: {sorted(RUN_STYLES)}") from None


def solid_color(cmap_name: str, alpha: float = 0.65):
    """A single solid RGBA sampled from a named colormap — the campaign
    scripts' `style.solid_color`, kept so a figure ported from there behaves
    identically."""
    return plt.get_cmap(cmap_name)(alpha)


