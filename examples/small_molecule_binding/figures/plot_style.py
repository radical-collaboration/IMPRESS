# A tight bounding box is right for a figure laid out by `tight_layout`, and
# wrong for one that sets its own margins: a long footer caption then stretches
# the canvas instead of wrapping. It cannot be an rcParam default either, since
# `bbox_inches=None` at the call site falls back to the rcParam rather than
# disabling it. So it is opt-in.
SAVE_TIGHT = dict(bbox_inches="tight")

LINE_KW = dict(linewidth=1.8, solid_capstyle="round", zorder=6)
MARKER_KW = dict(markersize=4, markerfacecolor="white", markeredgewidth=1.2,
                 zorder=6)
BAND_ALPHA = 0.15   # +/- 2 sigma envelopes
# Grid 0, bands 2, bars 3, lines/markers 6, annotations 7.
Z = dict(grid=0, band=2, bar=3, line=6, annot=7)


def apply_rcparams():
    plt.rcParams.update(RCPARAMS)


def line_kw(job: str, *, marker: bool = False, **over):
    """Line keywords for one run: validated hue, house geometry, legend label."""
    s = style_for(job)
    kw = dict(color=s.color, label=s.label, **LINE_KW)
    if marker:
        kw.update(marker=s.marker, markeredgecolor=s.color, **MARKER_KW)
    kw.update(over)
    return kw


def band_kw(job: str, **over):
    """Fill keywords for one run's +/- 2 sigma envelope."""
    s = style_for(job)
    kw = dict(color=s.color, alpha=BAND_ALPHA, linewidth=0, zorder=Z["band"])
    kw.update(over)
    return kw


def caption(fig, text, y: float = 0.005, bottom: float = 0.18):
    """Provenance or caveat caption along the bottom of a figure, reserving
    room so it never lands on the x-axis label."""
    if not text:
        return
    fig.text(0.5, y, text, ha="center", va="bottom", fontsize="small",
             color=INK_SECONDARY, wrap=True)
    fig.subplots_adjust(bottom=max(fig.subplotpars.bottom, bottom))


def direct_label(ax, x, y, text, color, *, dx=6, dy=0, ha="left", va="center",
                 weight="bold", size="medium"):
    """A label on the mark itself. Every series carries one, so identity never
    rests on hue alone."""
    ax.annotate(text, xy=(x, y), xytext=(dx, dy), textcoords="offset points",
                ha=ha, va=va, fontsize=size, color=color, fontweight=weight,
                zorder=Z["annot"],
                bbox=dict(boxstyle="round,pad=0.18", facecolor="white",
                          edgecolor="none", alpha=0.85))
